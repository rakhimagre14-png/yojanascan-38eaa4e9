type Ctx = { lang: LangCode; setLang: (l: LangCode) => void; t: (key: string) => string; dir: "ltr" | "rtl" };

const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>("en");

  useEffect(() => {
    const saved = typeof window !== "undefined" ? (localStorage.getItem("yojana-lang") as LangCode | null) : null;
    if (saved && dicts[saved]) setLangState(saved);
  }, []);

  const setLang = (l: LangCode) => {
    setLangState(l);
    try { localStorage.setItem("yojana-lang", l); } catch {}
  };

  const dir: "ltr" | "rtl" = lang === "ur" ? "rtl" : "ltr";

  const t = (key: string) => {
    const d = dicts[lang] ?? en;
    return d[key] ?? en[key] ?? key;
  };

  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = lang;
      document.documentElement.dir = dir;
    }
  }, [lang, dir]);

  return <I18nContext.Provider value={{ lang, setLang, t, dir }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
